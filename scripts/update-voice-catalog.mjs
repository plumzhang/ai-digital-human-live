import fs from 'node:fs/promises';

const source = 'https://platform.vidu.cn/vidu-stream/doc/voice-list?provider=ali';
const response = await fetch(source);
if (!response.ok) throw Error(`Voice documentation HTTP ${response.status}`);
const html = await response.text();
const flight = [...html.matchAll(/self\.__next_f\.push\((\[1,"(?:[^"\\]|\\.)*"\])\)/g)].map(match => JSON.parse(match[1])[1]).join('');
const marker = '"voiceCatalog":{"voices":';
const markerAt = flight.indexOf(marker);
if (markerAt < 0) throw Error('Voice catalog was not found in the official documentation');
const start = markerAt + marker.length;
let quoted = false, escaped = false, depth = 0, end = -1;
for (let i = start; i < flight.length; i++) {
  const char = flight[i];
  if (quoted) { if (escaped) escaped = false; else if (char === '\\') escaped = true; else if (char === '"') quoted = false; }
  else if (char === '"') quoted = true;
  else if (char === '[') depth++;
  else if (char === ']' && --depth === 0) { end = i + 1; break; }
}
if (end < 0) throw Error('Voice catalog array was incomplete');
const unique = new Map();
for (const voice of JSON.parse(flight.slice(start, end))) {
  if (voice.provider !== 'ali') continue;
  if (!voice.name || !voice.voiceType) throw Error('Voice catalog entry has no name or ID');
  const provider = 'qwen_omni';
  unique.set(`${provider}:${voice.voiceType}`, { provider, id: voice.voiceType, name: voice.name, description: voice.scene || '', languages: voice.language || '', domesticOnly: false });
}
const voices = [...unique.values()];
if (!voices.length || voices.some(voice => voice.provider !== 'qwen_omni')) throw Error('Only Qwen Omni realtime voices are allowed');
const output = `// Source: ${source}; generated by scripts/update-voice-catalog.mjs\nexport type BuiltinVoice = { provider: 'qwen_omni'; id: string; name: string; description: string; languages: string; domesticOnly: boolean };\nexport const builtinVoices: BuiltinVoice[] = ${JSON.stringify(voices, null, 2)};\n`;
await fs.writeFile(new URL('../src/voiceCatalog.ts', import.meta.url), output);
console.log(JSON.stringify({ qwen_omni: voices.length }));
